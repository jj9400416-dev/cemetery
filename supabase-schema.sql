create table if not exists public.graves (
  id bigint generated by default as identity primary key,
  name text not null,
  section text not null,
  level integer not null,
  birthdate text,
  dod text,
  x text not null default '50%',
  y text not null default '50%',
  created_at timestamptz not null default now()
);

alter table public.graves enable row level security;

drop policy if exists "Anyone can view graves" on public.graves;
create policy "Anyone can view graves"
  on public.graves for select
  using (true);

drop policy if exists "Anyone can add graves" on public.graves;
create policy "Anyone can add graves"
  on public.graves for insert
  with check (true);

drop policy if exists "Anyone can update graves" on public.graves;
create policy "Anyone can update graves"
  on public.graves for update
  using (true)
  with check (true);

drop policy if exists "Anyone can remove graves" on public.graves;
create policy "Anyone can remove graves"
  on public.graves for delete
  using (true);
