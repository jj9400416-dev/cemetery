-- Agnipa Memorial Park — visitor survey
-- Run once in Supabase Dashboard -> SQL Editor.
--
-- Two tables: one row per respondent (survey_responses) and one row per
-- answered question (survey_answers). The admin dashboard computes the
-- per-question weighted mean x̄ = Σ(f·w) / N from these rows.
--
-- PRIVACY NOTE: responses contain names, emails, and respondent-profile
-- details. The select policies below
-- mirror the app's existing anon-read style so the client-side admin dashboard
-- can read them. For production, restrict select to `authenticated` (Supabase
-- Auth) or move the aggregation behind a security-definer view.

create table if not exists public.survey_responses (
  id          bigint generated by default as identity primary key,
  name        text not null,
  email       text not null,
  consent     boolean not null default false,
  created_at  timestamptz not null default now()
);

-- Respondent-profile columns used by the evaluation form. They are nullable
-- because the instrument marks several items "when applicable". Safe to re-run.
alter table public.survey_responses add column if not exists age integer;
alter table public.survey_responses add column if not exists sex text;
alter table public.survey_responses add column if not exists relationship text;
alter table public.survey_responses add column if not exists visit_frequency text;
alter table public.survey_responses add column if not exists device_used text;
alter table public.survey_responses add column if not exists browser_used text;

alter table public.survey_responses drop constraint if exists survey_responses_age_check;
alter table public.survey_responses
  add constraint survey_responses_age_check check (age is null or age between 1 and 120);

create table if not exists public.survey_answers (
  id            bigint generated by default as identity primary key,
  response_id   bigint not null references public.survey_responses(id) on delete cascade,
  question_no   integer not null check (question_no between 1 and 15),
  question_text text not null,
  answer_value  smallint not null check (answer_value between 1 and 5),
  answer_label  text not null
);

-- If this table was created with the old 7-question survey, widen the
-- question range to 15. Safe to re-run.
alter table public.survey_answers
  drop constraint if exists survey_answers_question_no_check;
alter table public.survey_answers
  add constraint survey_answers_question_no_check check (question_no between 1 and 15);

create index if not exists idx_survey_answers_response on public.survey_answers (response_id);
create index if not exists idx_survey_answers_question on public.survey_answers (question_no);
create index if not exists idx_survey_responses_created on public.survey_responses (created_at desc);

alter table public.survey_responses enable row level security;
alter table public.survey_answers enable row level security;

-- Anyone may submit a response, but only with consent checked.
drop policy if exists "Anyone can submit responses" on public.survey_responses;
create policy "Anyone can submit responses"
  on public.survey_responses for insert
  to anon, authenticated
  with check (consent = true);

drop policy if exists "Anyone can submit answers" on public.survey_answers;
create policy "Anyone can submit answers"
  on public.survey_answers for insert
  to anon, authenticated
  with check (answer_value between 1 and 5);

-- Read access used by the admin results panel.
drop policy if exists "Anyone can view responses" on public.survey_responses;
create policy "Anyone can view responses"
  on public.survey_responses for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can view answers" on public.survey_answers;
create policy "Anyone can view answers"
  on public.survey_answers for select
  to anon, authenticated
  using (true);

-- Allow the admin dashboard to remove a response. Deleting the parent row
-- cascades to public.survey_answers via the FK, so no child policy is needed.
drop policy if exists "Admins can delete responses" on public.survey_responses;
create policy "Admins can delete responses"
  on public.survey_responses for delete
  to anon, authenticated
  using (true);

-- ---- atomic submit (optional but recommended) ------------------------------
-- Writes the response row and all of its answer rows in ONE transaction, so a
-- response can never be saved without its answers. Without this, a failed
-- answer insert leaves an empty response behind: it is counted in the admin
-- "Responses" total but skipped by N (the weighted-mean denominator), which
-- makes the two numbers disagree.
--
-- The app calls this first and falls back to two writes (with a rollback) if
-- the function is not installed. Safe to re-run.
-- The 3-argument version predates the respondent profile; drop it so the new
-- signature is the only one PostgREST can resolve.
drop function if exists public.submit_survey_response(text, text, jsonb);

create or replace function public.submit_survey_response(
  p_name    text,
  p_email   text,
  p_profile jsonb,
  p_answers jsonb
) returns bigint
language plpgsql
security invoker
as $$
declare
  v_id bigint;
  a    jsonb;
begin
  insert into public.survey_responses
    (name, email, consent, age, sex, relationship, visit_frequency, device_used, browser_used)
  values (
    p_name,
    p_email,
    true,
    nullif(p_profile->>'age', '')::integer,
    nullif(p_profile->>'sex', ''),
    nullif(p_profile->>'relationship', ''),
    nullif(p_profile->>'visit_frequency', ''),
    nullif(p_profile->>'device_used', ''),
    nullif(p_profile->>'browser_used', '')
  )
  returning id into v_id;

  for a in select * from jsonb_array_elements(p_answers)
  loop
    insert into public.survey_answers
      (response_id, question_no, question_text, answer_value, answer_label)
    values (
      v_id,
      (a->>'question_no')::integer,
      a->>'question_text',
      (a->>'answer_value')::smallint,
      a->>'answer_label'
    );
  end loop;

  return v_id;
end;
$$;

grant execute on function public.submit_survey_response(text, text, jsonb, jsonb)
  to anon, authenticated;

